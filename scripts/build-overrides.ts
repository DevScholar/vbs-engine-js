// Development tool, not part of the build: writes src/runtime/name-overrides.generated.ts from the
// names-<lcid>.txt dumps a cscript run produces.
//
// Those dumps are not kept in the repository, so running this needs them: each is UTF-16LE and holds
// "<n>=<FormatDateTime(d, vbLongDate)>" for the 15th of every month of 2026 and for 5..11 January 2026,
// written through FileSystemObject.CreateTextFile(path, True, True) so the console's code page cannot lose
// the characters. A locale's month and weekday are then each read with the one LongDate pattern it has, so
// nothing is inferred from punctuation.
//
// Usage: node scripts/build-overrides.ts <dump-dir> <out-file>
import { readFileSync, writeFileSync } from 'node:fs';

const dir = process.argv[2];
const out = process.argv[3];
if (!dir || !out) throw new Error('usage: build-overrides.ts <dump-dir> <out-file>');

/** The pattern each locale's month and weekday are read with. Each expects one capture group. */
const EXTRACTORS: Record<number, { month: RegExp; weekday?: RegExp }> = {
  // "15. janvāris"; "pirmdiena, 2026. gada 15. janvāris".
  1062: { month: /gada \d+\.\s*(.+)$/, weekday: /^(.+?),/ },
  // "15 Tháng Giêng 2026".
  1066: { month: /^\d+\s+(.+?)\s+\d{4}$/ },
  // "2026 Phesekgong 15, Mmantaha".
  1072: { month: /^\d{4}\s+(.+?)\s+\d+,/, weekday: /,\s*(.+)$/ },
  1073: { month: /^\d{4}\s+(.+?)\s+\d+,/, weekday: /,\s*(.+)$/ },
  1074: { month: /^\d{4}\s+(.+?)\s+\d+,/, weekday: /,\s*(.+)$/ },
  // "15 दिसम्बर 2026".
  1081: { month: /^\d+\s+(.+?)\s+\d{4}$/ },
  // "‏15 ‏جانفييه, ‏2026" - the marks a right-to-left locale writes come off first.
  5121: { month: /^\d+\s+(.+?),\s*\d{4}$/ },
  7169: { month: /^\d+\s+(.+?),\s*\d{4}$/ },
};

/** A dump line with the directional marks removed, which one of them writes around every field. */
const withoutMarks = (value: string): string => value.replace(/[\u200e\u200f]/g, '');

/** The names Windows writes for one locale. */
function readNames(lcid: number): { months: string[]; weekdays: string[] } {
  const extractor = EXTRACTORS[lcid];
  if (!extractor) throw new Error(`no extractor for ${lcid}`);
  const months: string[] = [];
  const weekdays: string[] = [];
  for (const line of readFileSync(`${dir}\\names-${lcid}.txt`, 'utf16le').split(/\r?\n/)) {
    if (!line.includes('=')) continue;
    const at = line.indexOf('=');
    const key = line.slice(0, at);
    const value = withoutMarks(line.slice(at + 1));
    if (key.startsWith('w')) {
      if (!extractor.weekday) continue;
      const found = extractor.weekday.exec(value);
      if (!found) throw new Error(`${lcid}: weekday not found in ${JSON.stringify(value)}`);
      weekdays[(Number(key.slice(1)) - 5 + 1) % 7] = found[1];
    } else {
      const found = extractor.month.exec(value);
      if (!found) throw new Error(`${lcid}: month not found in ${JSON.stringify(value)}`);
      months[Number(key) - 1] = found[1];
    }
  }
  return { months, weekdays };
}

/** A `months: { … }` / `weekdays: { … }` property, at the indentation the block uses. */
function property(name: 'months' | 'weekdays', names: string[], only?: number[]): string {
  const lines = [`    ${name}: {`];
  names.forEach((value, index) => {
    if (only && !only.includes(index)) return;
    lines.push(`      ${index}: ${JSON.stringify(value)},`);
  });
  lines.push('    },');
  return lines.join('\n');
}

const header = `// Generated by scripts/build-overrides.ts - do not edit by hand.
//
// The month and weekday names Windows writes for the few locales where CLDR has moved on since, read off
// FormatDateTime(d, vbLongDate) for each named instant in the cscript oracle. They are data rather than a
// patch on top of Intl because there is nothing in either source that says which spelling vbscript.dll
// used, and a listing keeps that difference visible instead of hidden in a fallback.
//
// Keyed by LCID; a month is keyed by a zero-based month (January is 0) and a weekday by getUTCDay, which
// puts Sunday at 0. A locale absent here takes every one of its names from Intl.
//
// Regenerating needs the names-<lcid>.txt dumps the build tool reads; see its header for their format.

/** The names one locale spells differently from Intl. */
export interface NameOverrides {
  /** The months Windows names differently. */
  months?: Record<number, string>;
  /** The weekdays Windows names differently. */
  weekdays?: Record<number, string>;
}
`;

const entries: string[] = [
  'export const NAME_OVERRIDES: Record<number, NameOverrides> = {',
  '  // Latvian: Intl capitalizes the weekday, Windows writes it lower case inside a date.',
  '  1062: {',
  property('weekdays', readNames(1062).weekdays),
  '  },',
  '  // Vietnamese: Windows uses the traditional month names, CLDR the numbered "tháng 1" form.',
  '  1066: {',
  property('months', readNames(1066).months),
  '  },',
  '  // Southern Sotho: CLDR has revised these names since Windows shipped them.',
  '  1072: {',
  property('months', readNames(1072).months),
  property('weekdays', readNames(1072).weekdays),
  '  },',
  '  // Tsonga: no ICU data at all, so every one of its names comes from here. The runtime resolves',
  "  // 'ts' to the host locale, which is how another language's names were reaching it.",
  '  1073: {',
  property('months', readNames(1073).months),
  property('weekdays', readNames(1073).weekdays),
  '  },',
  '  // Tswana: CLDR has revised these names since Windows shipped them.',
  '  1074: {',
  property('months', readNames(1074).months),
  property('weekdays', readNames(1074).weekdays),
  '  },',
  '  // Hindi: Windows writes the December name with the conjunct "म्ब", CLDR with "ंब". Only that one',
  '  // differs, so the other eleven keep coming from Intl.',
  '  1081: {',
  property('months', readNames(1081).months, [11]),
  '  },',
  '  // Algerian and Tunisian Arabic: Windows writes its own French-derived month names for this calendar,',
  '  // which CLDR has since replaced with the Mashriqi ones ("جانفي" against Windows\'s "جانفييه").',
  '  5121: {',
  property('months', readNames(5121).months),
  '  },',
  '  7169: {',
  property('months', readNames(7169).months),
  '  },',
  '};',
];
writeFileSync(out, header + entries.join('\n') + '\n', 'utf8');
console.log(`wrote ${out}`);
