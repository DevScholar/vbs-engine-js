// Emits src/builtins/locale-data.generated.ts: for every LCID the engine knows, the locale name to use
// with Intl.
//
// Windows' own name (LCIDToLocaleName, read by the PowerShell wrapper) is authoritative, but ICU does
// not know every Windows name - "es-ES_tradnl" makes Intl.DateTimeFormat throw, and "en-029" falls
// back to plain "en". Passing a name ICU rejects is worse than the name the engine already used, so a
// name is adopted only when ICU resolves it exactly; otherwise the hand-written name is kept and the
// LCID is listed in the exceptions.
import { readFileSync, writeFileSync } from 'node:fs';

const [namesPath, localeSourcePath, outPath] = process.argv.slice(2);

const windowsNames = new Map();
for (const line of readFileSync(namesPath, 'utf8').trim().split(/\r?\n/)) {
  const [lcid, name] = line.split('|');
  if (name) windowsNames.set(Number(lcid), name);
}

// The hand-written map, as the fallback for the LCIDs whose Windows name ICU cannot use.
const handwritten = new Map();
for (const match of readFileSync(localeSourcePath, 'utf8').matchAll(/\['([^']+)',\s*(\d+)\]/g)) {
  const lcid = Number(match[2]);
  if (!handwritten.has(lcid)) handwritten.set(lcid, match[1]);
}

const resolvesExactly = name => {
  try {
    const resolved = new Intl.DateTimeFormat(name).resolvedOptions().locale;
    return resolved.toLowerCase().replace(/_/g, '-') === name.toLowerCase().replace(/_/g, '-');
  } catch {
    return false;
  }
};

const chosen = [];
const exceptions = [];
const missing = [];
// Every LCID either side knows: one of them (1084, Scottish Gaelic) has no Windows name at all, and
// dropping it here would take the engine's name away with it.
const allLcids = [...new Set([...windowsNames.keys(), ...handwritten.keys()])].sort((a, b) => a - b);
for (const lcid of allLcids) {
  const windowsName = windowsNames.get(lcid);
  if (windowsName && resolvesExactly(windowsName)) {
    // Lower case, to match the names the engine already used: lookups such as the currency table are
    // case sensitive, and BCP 47 tags are case insensitive anyway.
    chosen.push([lcid, windowsName.toLowerCase()]);
    continue;
  }
  const fallback = handwritten.get(lcid);
  if (!fallback) {
    missing.push(`${lcid} (${windowsName ?? 'no Windows name'})`);
    continue;
  }
  chosen.push([lcid, fallback.toLowerCase()]);
  exceptions.push(windowsName ? `${lcid}: ${fallback} (Windows says ${windowsName})` : `${lcid}: ${fallback} (Windows has no name)`);
}

const rows = chosen.map(([lcid, name]) => `  [${lcid}, '${name}'],`).join('\n');
const header = `// Generated by scripts/generate-locale-names.ps1 - do not edit by hand.
//
// The locale name to use with Intl for each LCID the engine knows. Windows' own name
// (LCIDToLocaleName) is used wherever ICU resolves it exactly; otherwise the name the engine already
// used is kept, so a name ICU would reject or silently redirect is never passed to it.
//
// Generated on Windows build ${process.env.WINDOWS_BUILD ?? 'unknown'} with Node ${process.version},
// ICU ${process.versions.icu}, CLDR ${process.versions.cldr}.

/**
 * LCIDs whose Windows name ICU cannot resolve exactly, and the name kept in its place:
${exceptions.map(exception => ` * - ${exception}`).join('\n')}
 */
export const LCID_TO_LOCALE: ReadonlyMap<number, string> = new Map([
${rows}
]);
`;

writeFileSync(outPath, header, 'utf8');
console.log(`rows: ${chosen.length}   kept a non-Windows name: ${exceptions.length}`);
for (const exception of exceptions) console.log(`  ${exception}`);
if (missing.length > 0) console.log(`no name at all: ${missing.join(', ')}`);
